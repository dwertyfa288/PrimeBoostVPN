  let language = "ru";

  function t(key, vars) {
    const value = (dictionaries[language] || dictionaries.ru)[key] ?? dictionaries.ru[key] ?? key;
    if (!vars || typeof value !== "string") {
      return value;
    }
    return value.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : ""));
  }

  function setLanguage(code) {
    language = String(code || "").toLowerCase().startsWith("ru") ? "ru" : "en";
    document.documentElement.lang = language;
    document.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = t(node.dataset.i18n);
    });
  }

